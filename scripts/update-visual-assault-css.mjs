// Vendors VisualAssault's CSS theme package at a given tag into src/core/themes.generated.ts, so the report
// page (which must be one file with no network) carries the shared themes without a hand-copied palette.
//
//   node scripts/update-visual-assault-css.mjs v0.2.0          write the file for that tag
//   node scripts/update-visual-assault-css.mjs v0.2.0 --check  fail if the committed file differs
//   node scripts/update-visual-assault-css.mjs --check         the same, for the tag the file says it is from
//
// Bumping the theme is deliberate: run this with the new tag and commit the result on its own (see
// KVG_Standards' themes-versioning.md). Never edit the generated file by hand.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const out = fileURLToPath(new URL('../src/core/themes.generated.ts', import.meta.url))
let tag = process.argv[2]
if ((!tag || tag.startsWith('--')) && process.argv.includes('--check')) {
  try {
    tag = /VISUAL_ASSAULT_TAG = "([^"]+)"/.exec(readFileSync(out, 'utf8'))?.[1]
  } catch {}
}
if (!tag || !/^v\d+\.\d+\.\d+$/.test(tag)) {
  console.error('Usage: node scripts/update-visual-assault-css.mjs vX.Y.Z [--check]')
  process.exit(2)
}
const url = `https://raw.githubusercontent.com/gerp93/VisualAssault/${tag}/packages/css/themes.css`

const res = await fetch(url)
if (!res.ok) {
  console.error(`Could not fetch ${url}: ${res.status}`)
  process.exit(1)
}
const css = (await res.text()).replace(/\r\n/g, '\n')
const ids = [...css.matchAll(/^body\.([a-z0-9-]+-theme)\s*\{/gm)].map(m => m[1])
if (ids.length === 0) {
  console.error('No themes found in the fetched CSS; the package layout may have changed.')
  process.exit(1)
}

const source =
  `// GENERATED by scripts/update-visual-assault-css.mjs from VisualAssault ${tag}. Do not edit by hand.\n` +
  `// Source: ${url}\n\n` +
  `/** The VisualAssault tag these themes were vendored from. */\n` +
  `export const VISUAL_ASSAULT_TAG = ${JSON.stringify(tag)}\n\n` +
  `/** Theme ids, each applied by putting it as the class of <body>. */\n` +
  `export const THEME_IDS: readonly string[] = ${JSON.stringify(ids, null, 2)}\n\n` +
  `/** The themes' stylesheet, verbatim. */\n` +
  `export const THEMES_CSS = ${JSON.stringify(css)}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n')
  } catch {}
  if (current !== source) {
    console.error(`src/core/themes.generated.ts is not the VisualAssault ${tag} package. Run: node scripts/update-visual-assault-css.mjs ${tag}`)
    process.exit(1)
  }
  console.log(`themes.generated.ts matches VisualAssault ${tag}`)
} else {
  writeFileSync(out, source)
  console.log(`Wrote ${out} (${ids.length} themes from ${tag})`)
}
