// Writes types/index.d.ts, the Claude engine's contract for what this plugin keeps in `$.state`.
//
// The engine reads that file on its own: it must be self-contained (no imports) and may only export
// types. But the shapes belong to the core, written once in src/core/types.ts for every outlet. So the
// contract is generated: the core's types, verbatim, then what is specific to the pane.
//
//   node scripts/sync-contract.mjs          write types/index.d.ts
//   node scripts/sync-contract.mjs --check  exit 1 if it is out of date (a test also checks this)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lf = text => text.replace(/\r\n/g, '\n')

const HEADER = `// GENERATED by scripts/sync-contract.mjs from src/core/types.ts. Do not edit by hand: change the core's
// types and run the script. (The engine needs this file self-contained, so the core's types are copied
// in verbatim below, then what is specific to the Claude pane.)

`

const FOOTER = `
// ---- Specific to the Claude pane ----------------------------------------------------------------

/** Which of the pane's two views is showing. */
export type ViewName = 'dashboard' | 'stats'

declare module 'claude-code' {
  interface PluginState {
    'shipwatch': { board: Board; showStale: boolean; view: ViewName; stats: StatsBoard }
  }
}
`

const core = lf(readFileSync(join(root, 'src/core/types.ts'), 'utf8')).trimEnd() + '\n'
const wanted = HEADER + core + FOOTER
const target = join(root, 'types/index.d.ts')

if (process.argv.includes('--check')) {
  const current = lf(readFileSync(target, 'utf8'))
  if (current !== wanted) {
    console.error('types/index.d.ts is out of date: run `node scripts/sync-contract.mjs`.')
    process.exit(1)
  }
  console.log('types/index.d.ts is up to date.')
} else {
  writeFileSync(target, wanted)
  console.log('Wrote types/index.d.ts')
}
